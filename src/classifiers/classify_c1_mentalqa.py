def categories_to_multihot(cat_list, cat2id):
    """
    Convert a list of labels (e.g. ["A","C"]) into a multi-hot vector
    using the mapping cat2id.
    """
    num_labels = len(cat2id)
    vec = np.zeros(num_labels, dtype=int)
    for cat in cat_list:
        if cat in cat2id:  # double-check label is valid
            vec[cat2id[cat]] = 1
    return vec


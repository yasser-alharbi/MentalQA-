def multi_label_metrics(eval_pred):
    logits, labels = eval_pred
    # Apply sigmoid
    probs = 1 / (1 + np.exp(-logits))
    # Binarize predictions
    y_pred = (probs > 0.5).astype(int)

    # Flatten or not? Because it's multi-label, we do it label-wise
    precision, recall, f1, _ = precision_recall_fscore_support(labels, y_pred, average='micro')
    acc = accuracy_score(labels, y_pred)  # Not super informative for multi-label, but we can compute it

    return {
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "accuracy": acc
    }


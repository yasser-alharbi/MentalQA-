def random_deletion(words, p=0.1):
    """
    Randomly deletes each word with probability p.
    words: list of tokens.
    """
    # If only one word, just return it
    if len(words) == 1:
        return words

    new_words = []
    for w in words:
        # With probability p, drop the word
        if random.uniform(0,1) > p:
            new_words.append(w)
    # If everything deleted, return 1 word
    if len(new_words) == 0:
        return [random.choice(words)]
    return new_words
#2
def random_swap(words, n=1):
    """
    Randomly swap the positions of two words n times.
    words: list of tokens
    """
    new_words = words.copy()
    for _ in range(n):
        idx1, idx2 = random.sample(range(len(new_words)), 2)
        new_words[idx1], new_words[idx2] = new_words[idx2], new_words[idx1]
    return new_words
#3
def augment_text_arabic(text, alpha_delete=0.1, swaps=1):
    """
    Apply random_deletion + random_swap to text and return multiple augmented variants.
    """
    words = text.split()

    # 1) Random Deletion
    words_del = random_deletion(words, p=alpha_delete)
    text_del = " ".join(words_del)

    # 2) Random Swap
    words_swap = random_swap(words, n=swaps)
    text_swap = " ".join(words_swap)

    return [text_del, text_swap]


def predict_labels(texts, threshold=0.9):
    # If user passes a single string, make it a list for uniform processing
    if isinstance(texts, str):
        texts = [texts]

    # Tokenize (batch)
    inputs = tokenizer_past(
        texts,
        return_tensors="pt",
        padding=True,
        truncation=True,
        max_length=128
    )

    with torch.no_grad():
        outputs = model_past(**inputs)
        # shape [batch_size, num_labels]
        logits = outputs.logits

    # Convert logits -> probabilities
    probs = torch.sigmoid(logits).cpu().numpy()

    # Threshold
    predictions = (probs > threshold).astype(int)

    # Decode label indices to label names
    all_results = []
    for pred_row in predictions:
        label_indices = np.where(pred_row == 1)[0]
        predicted_labels = [all_cats[idx] for idx in label_indices]
        all_results.append(predicted_labels)

    return all_results

